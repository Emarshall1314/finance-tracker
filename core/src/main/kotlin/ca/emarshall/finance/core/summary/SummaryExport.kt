data class SummaryAccount(val nickname: String, val type: String, val institution: String)

data class InvestmentAccountSummary(val nickname: String, val type: String, val equityCents: Long, val cashCents: Long)

data class HoldingSummary(val symbol: String, val quantity: String, val marketValueCents: Long, val openPnlCents: Long?)

data class InvestmentSummary(
    /** Combined CAD, from Questrade's combined balances. */
    val totalEquityCents: Long,
    val accounts: List<InvestmentAccountSummary>,
    val holdings: List<HoldingSummary>,
    val dividendsLast12MonthsCents: Long,
    val dividendsThisYearCents: Long,
    /** Deposits this calendar year by account type (TFSA, RRSP, FHSA, ...). */
    val contributionsThisYearByType: Map<String, Long>,
)

data class SummaryInput(
    val from: LocalDate,
    val to: LocalDate,
    val accounts: List<SummaryAccount>,
    val facts: List<TxFact>,
    val bills: List<RecurringSeries>,
    val balances: List<AccountBalance>,
    val netWorthTrend: List<Pair<YearMonth, Long>>,
    val investments: InvestmentSummary?,
)

/**
 * Builds the Markdown report a person pastes into Claude for advice. It uses nicknames only and masks
 * anything that looks like an account or card number in free text.
 */
object SummaryExport {

    private val MONTH = DateTimeFormatter.ofPattern("MMM yyyy", Locale.ENGLISH)
    private val DAY = DateTimeFormatter.ofPattern("MMM d, yyyy", Locale.ENGLISH)

    fun markdown(input: SummaryInput): String {
        val a = Analytics(input.facts)
        val months = monthsBetween(input.from, input.to)
        val sb = StringBuilder()
        fun line(s: String = "") = sb.append(s).append('\n')
        fun m(c: Long) = Money.format(c)

        line("# My finances: ${input.from.format(DAY)} to ${input.to.format(DAY)}")
        line()
        line("Context for this summary:")
        line("- I live in British Columbia, Canada. All amounts are in Canadian dollars (CAD) unless marked.")
        line("- Period covered: ${input.from} to ${input.to} (${months.size} months).")
        line("- Transfers between my own accounts (card payments, moving money to investments) are excluded from income and spending.")
        line("- Generated by my personal finance tracker from bank exports and Questrade. Account numbers are omitted.")
        line()

        line("## Accounts")
        line()
        line("| Account | Type | Institution |")
        line("|---|---|---|")
        input.accounts.forEach { line("| ${cell(it.nickname)} | ${it.type} | ${it.institution} |") }
        line()

        line("## Monthly income, spending and net")
        line()
        line("| Month | Income | Spending | Net | Savings rate |")
        line("|---|---:|---:|---:|---:|")
        var totIn = 0L
        var totOut = 0L
        months.forEach { mo ->
            val t = a.monthTotals(mo)
            totIn += t.incomeCents; totOut += t.spendingCents
            line("| ${mo.format(MONTH)} | ${m(t.incomeCents)} | ${m(t.spendingCents)} | ${m(t.netCents)} | ${t.savingsRatePercent?.let { "$it%" } ?: "–"} |")
        }
        val rate = if (totIn > 0) "${Math.round((totIn - totOut) * 100.0 / totIn)}%" else "–"
        line("| **Total** | **${m(totIn)}** | **${m(totOut)}** | **${m(totIn - totOut)}** | **$rate** |")
        line()

        line("## Spending by category per month")
        line()
        val cats = a.spendingByCategory(input.from, input.to)
        if (cats.isEmpty()) {
            line("No spending recorded.")
        } else {
            line("| Category | " + months.joinToString(" | ") { it.format(MONTH) } + " | Total | Monthly avg |")
            line("|---|" + months.joinToString("") { "---:|" } + "---:|---:|")
            val perMonth = months.associateWith { mo -> a.spendingByCategory(mo).associate { it.categoryKey to it.cents } }
            cats.forEach { c ->
                val cellsText = months.joinToString(" | ") { mo -> m(perMonth[mo]?.get(c.categoryKey) ?: 0L) }
                line("| ${cell(c.categoryName)} | $cellsText | ${m(c.cents)} | ${m(c.cents / months.size.coerceAtLeast(1))} |")
            }
        }
        line()

        line("## Top merchants")
        line()
        val merchants = a.topMerchants(input.from, input.to, 15)
        if (merchants.isEmpty()) line("None.") else {
            line("| Merchant | Total | Transactions |")
            line("|---|---:|---:|")
            merchants.forEach { line("| ${cell(it.merchant)} | ${m(it.cents)} | ${it.count} |") }
        }
        line()

        line("## Bills and subscriptions")
        line()
        if (input.bills.isEmpty()) line("None detected.") else {
            line("| Merchant | Typical monthly cost | Seen | Next expected |")
            line("|---|---:|---:|---|")
            input.bills.forEach {
                line("| ${cell(it.merchant)} | ${Money.format(it.monthlyCostCents, it.currency, true)} | ${it.occurrences}× | ${it.nextExpected.format(DAY)} |")
            }
            val monthly = input.bills.filter { it.currency == "CAD" }.sumOf { it.monthlyCostCents }
            line()
            line("Total recurring: about ${m(monthly)} per month.")
        }
        line()

        line("## Fees and interest")
        line()
        val fees = a.feeTransactions(input.from, input.to)
        if (fees.isEmpty()) line("None.") else {
            line("Total paid: ${m(a.feesAndInterest(input.from, input.to))}")
            line()
            fees.groupBy { YearMonth.from(it.date) }.toSortedMap().forEach { (mo, l) ->
                line("- ${mo.format(MONTH)}: ${m(-l.sumOf { it.amountCents })} (" + l.joinToString("; ") { cell(it.merchant) } + ")")
            }
        }
        line()

        line("## Balances and net worth")
        line()
        if (input.balances.isEmpty()) line("No balances recorded.") else {
            line("| Account | Balance | As of |")
            line("|---|---:|---|")
            input.balances.forEach { line("| ${cell(it.nickname)} | ${Money.format(it.balanceCents, it.currency, true)} | ${it.asOf.format(DAY)} |") }
            line()
            line("Net worth (CAD): **${m(input.balances.filter { it.currency == "CAD" }.sumOf { it.balanceCents })}**")
            if (input.netWorthTrend.size > 1) {
                line()
                line("Trend (month end): " + input.netWorthTrend.joinToString(", ") { (mo, v) -> "${mo.format(MONTH)} ${m(v)}" })
            }
        }
        line()

        line("## Investments (Questrade)")
        line()
        val inv = input.investments
        if (inv == null) line("Not connected.") else {
            line("Total equity (combined, CAD): **${m(inv.totalEquityCents)}**")
            line()
            line("| Account | Type | Equity | Cash |")
            line("|---|---|---:|---:|")
            inv.accounts.forEach { line("| ${cell(it.nickname)} | ${it.type} | ${m(it.equityCents)} | ${m(it.cashCents)} |") }
            line()
            val totalMv = inv.holdings.sumOf { it.marketValueCents }
            if (inv.holdings.isNotEmpty()) {
                line("### Holdings and allocation")
                line()
                line("| Symbol | Quantity | Market value | % of holdings | Open P&L |")
                line("|---|---:|---:|---:|---:|")
                inv.holdings.sortedByDescending { it.marketValueCents }.forEach { h ->
                    val pct = if (totalMv > 0) String.format(Locale.ENGLISH, "%.1f%%", h.marketValueCents * 100.0 / totalMv) else "–"
                    line("| ${cell(h.symbol)} | ${h.quantity} | ${m(h.marketValueCents)} | $pct | ${h.openPnlCents?.let { m(it) } ?: "–"} |")
                }
                line()
            }
            line("Dividends: ${m(inv.dividendsLast12MonthsCents)} in the last 12 months, ${m(inv.dividendsThisYearCents)} this year.")
            line()
            if (inv.contributionsThisYearByType.isNotEmpty()) {
                line("Contributions (deposits) this year by account type: " +
                    inv.contributionsThisYearByType.entries.sortedBy { it.key }.joinToString(", ") { "${it.key} ${m(it.value)}" } + ".")
                line("(Contribution room is not tracked here.)")
            }
        }
        val foreign = a.foreignCurrencyTotals(input.from, input.to)
        if (foreign.isNotEmpty()) {
            line()
            line("## Other currencies (not converted, not in totals above)")
            line()
            foreign.forEach { (cur, t) -> line("- $cur: income ${Money.format(t.incomeCents)} $cur, spending ${Money.format(t.spendingCents)} $cur") }
        }
        return sb.toString().trimEnd() + "\n"
    }

    fun monthsBetween(from: LocalDate, to: LocalDate): List<YearMonth> {
        val out = ArrayList<YearMonth>()
        var m = YearMonth.from(from)
        val end = YearMonth.from(to)
        while (!m.isAfter(end)) { out.add(m); m = m.plusMonths(1) }
        return out
    }

    /** Masks digit runs long enough to be account, card or reference numbers. */
    fun maskNumbers(s: String): String = s.replace(Regex("\\d[\\d -]{5,}\\d")) { mr ->
        if (mr.value.count { it.isDigit() } >= 6) "[number]" else mr.value
    }

    private fun cell(s: String) = maskNumbers(s).replace("|", "/").replace("\n", " ")
}

object TransactionCsvExport {
    data class Row(
        val date: LocalDate,
        val account: String,
        val merchant: String,
        val description: String,
        val category: String,
        val amountCents: Long,
        val currency: String,
        val notes: String?,
    )

    fun csv(rows: List<Row>): String {
        val sb = StringBuilder("date,account,merchant,description,category,amount,currency,notes\n")
        rows.sortedBy { it.date }.forEach { r ->
            sb.append(listOf(
                r.date.toString(), r.account, r.merchant, SummaryExport.maskNumbers(r.description), r.category,
                Money.fromCents(r.amountCents).toPlainString(), r.currency, r.notes.orEmpty(),
            ).joinToString(",") { quote(it) }).append('\n')
        }
        return sb.toString()
    }

    private fun quote(s: String): String =
        if (s.any { it == ',' || it == '"' || it == '\n' || it == '\r' }) "\"" + s.replace("\"", "\"\"") + "\"" else s
}
